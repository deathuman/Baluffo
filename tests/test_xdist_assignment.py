"""Self-test for the worker-assignment recorder in ``tests/helpers/xdist_assignment.py``.

The recorder exists because xdist does not say which worker ran which file, so a cross-file leak is
diagnosable only after the fact. That value depends on three things holding, and each is pinned
here: the record is actually produced by a real sharded session (driven end to end in a child
pytest with ``-n 2``), a record that cannot be trusted is dropped rather than guessed at, and the
replay command names exactly the files the recorded worker ran, in the order it ran them.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

from tests.helpers.xdist_assignment import load_runs, main, replay_command

_REPO_ROOT = Path(__file__).resolve().parents[1]

# Two tests per file: enough that a file's count is distinguishable from its presence, and cheap
# enough that a four-file sharded child is a few seconds rather than a suite.
_CHILD_TEST = """\
# Generated by tests/test_xdist_assignment.py: one file of the sharded child session.


def test_first() -> None:
    assert True


def test_second() -> None:
    assert True
"""


def _run_sharded_child(records_root: Path) -> subprocess.CompletedProcess[str]:
    """Run four trivial files under ``-n 2 --dist=loadfile`` with the recorder as a plugin.

    The child gets its own rootdir, so the repository conftest -- and with it the session lock --
    does not apply; the recorder is loaded by name, which is the same object the suite's conftest
    calls. Its records are redirected into ``records_root`` instead of the shared ``.tmp`` root.
    """

    child_root = Path(tempfile.mkdtemp(prefix="baluffo-xdist-assignment-child-"))
    try:
        for letter in ("a", "b", "c", "d"):
            (child_root / f"test_{letter}.py").write_text(_CHILD_TEST, encoding="utf-8")
        env = dict(os.environ)
        env["PYTHONPATH"] = str(_REPO_ROOT)
        env["BALUFFO_XDIST_ASSIGNMENTS_DIR"] = str(records_root)
        env.pop("PYTEST_ADDOPTS", None)
        return subprocess.run(
            [
                sys.executable,
                "-m",
                "pytest",
                # A relative argument, with the child's own directory as cwd: pytest then walks
                # only the directories it did not have to leave, so it never lists the shared
                # temp root where other workers' directories appear and disappear mid-run.
                ".",
                "-q",
                "--color=no",
                "-n",
                "2",
                "--dist=loadfile",
                "--rootdir",
                str(child_root),
                "--basetemp",
                str(child_root / "basetemp"),
                "-p",
                "no:cacheprovider",
                "-p",
                "tests.helpers.xdist_assignment",
            ],
            cwd=child_root,
            env=env,
            capture_output=True,
            text=True,
            timeout=300,
        )
    finally:
        shutil.rmtree(child_root, ignore_errors=True)


def test_a_sharded_session_records_one_worker_per_file(tmp_path: Path) -> None:
    """End to end: a real ``-n 2`` run leaves records that account for every file exactly once."""

    records_root = tmp_path / "records"
    proc = _run_sharded_child(records_root)

    output = proc.stdout + proc.stderr
    assert proc.returncode == 0, f"the sharded child failed:\n{output}"

    # This test spawned the child, so the child is a nested session: recorded, but not a run a
    # person would want to replay, and therefore absent from the default listing.
    assert load_runs(records_root) == [], "a child session must not be listed as a run"
    runs = load_runs(records_root, include_nested=True)
    assert len(runs) == 1, f"one session must leave one run, got {[run['run'] for run in runs]}"

    workers = runs[0]["workers"]
    for worker in workers:
        assert worker["nested"] is True, worker
        assert "test_xdist_assignment.py" in str(worker["spawned_by"]), worker
    assert len(workers) == 2, f"four files on two workers must use both: {workers}"

    # ``--dist=loadfile`` never splits a file, which is what makes a per-worker file list a
    # faithful record of the process each file ran in.
    recorded = [entry["path"] for worker in workers for entry in worker["files"]]
    assert sorted(recorded) == ["test_a.py", "test_b.py", "test_c.py", "test_d.py"], recorded
    assert len(recorded) == len(set(recorded)), f"a file ran on two workers: {recorded}"

    for worker in workers:
        assert worker["tests"] == 2 * len(worker["files"]), worker
        assert worker["worker"].startswith("gw"), worker


def test_replay_command_names_that_workers_files_in_its_own_order(tmp_path: Path) -> None:
    """The replay is one process over exactly one worker's files, in the order that worker ran them."""

    records_root = tmp_path / "records"
    proc = _run_sharded_child(records_root)
    assert proc.returncode == 0, proc.stdout + proc.stderr

    worker = load_runs(records_root, include_nested=True)[0]["workers"][0]
    paths = [entry["path"] for entry in worker["files"]]
    command = replay_command(worker)
    # The printed command is separator-normalized so a copied one survives a POSIX shell.
    rootdir = Path(worker["rootdir"]).as_posix()

    assert command.startswith("python -m pytest "), command
    assert command.endswith("-q --rootdir=" + rootdir), command
    named = command.removeprefix("python -m pytest ").removesuffix(" -q --rootdir=" + rootdir)
    assert named.split(" ") == paths, f"{command} does not match {paths}"


def test_nested_records_are_hidden_unless_asked_for(tmp_path: Path) -> None:
    """A run list is for runs: a child pytest session needs ``--all`` to appear."""

    def write(directory: Path, worker: str) -> None:
        directory.mkdir(parents=True)
        record: dict[str, Any] = {
            "run": directory.name.removeprefix("run-"),
            "worker": worker,
            "nested": directory.parent.name == "nested",
            "spawned_by": "tests/example.py::test_parent" if directory.parent.name else None,
            "rootdir": str(tmp_path),
            "tests": 1,
            "files": [{"path": "test_kept.py", "tests": 1}],
        }
        (directory / f"worker-{worker}.json").write_text(json.dumps(record), encoding="utf-8")

    write(tmp_path / "run-real", "solo")
    write(tmp_path / "nested" / "nested-child", "solo-1234")

    assert [run["run"] for run in load_runs(tmp_path)] == ["real"]
    assert sorted(run["run"] for run in load_runs(tmp_path, include_nested=True)) == [
        "child",
        "real",
    ]


def test_list_shows_nested_sessions_only_with_all(tmp_path: Path, capsys: Any) -> None:
    """The listing is the interface that hid the child sessions; pin both directions of it."""

    for directory, worker in (
        (tmp_path / "run-real", "solo"),
        (tmp_path / "nested" / "nested-c", "solo-1"),
    ):
        directory.mkdir(parents=True)
        record: dict[str, Any] = {
            "run": directory.name,
            "worker": worker,
            "nested": directory.parent.name == "nested",
            "spawned_by": "tests/example.py::test_parent" if directory.parent.name else None,
            "rootdir": str(tmp_path),
            "tests": 1,
            "files": [{"path": "test_kept.py", "tests": 1}],
        }
        (directory / f"worker-{worker}.json").write_text(json.dumps(record), encoding="utf-8")

    assert main(["--root", str(tmp_path), "--list"]) == 0
    plain = capsys.readouterr().out
    assert "real" in plain and "[nested]" not in plain, plain

    assert main(["--root", str(tmp_path), "--list", "--all"]) == 0
    everything = capsys.readouterr().out
    assert "[nested]" in everything, everything


def test_an_unreadable_or_foreign_record_is_dropped(tmp_path: Path) -> None:
    """A truncated write or a stray file must not become a replay target."""

    run_dir = tmp_path / "run-abandoned"
    run_dir.mkdir()
    good: dict[str, Any] = {
        "run": "abandoned",
        "worker": "gw1",
        "rootdir": str(tmp_path),
        "tests": 2,
        "files": [{"path": "test_kept.py", "tests": 2}],
    }
    (run_dir / "worker-gw1.json").write_text(json.dumps(good), encoding="utf-8")
    (run_dir / "worker-gw0.json").write_text('{"run": "abandoned", "files": [', encoding="utf-8")
    (run_dir / "worker-gw2.json").write_text('{"run": "abandoned"}', encoding="utf-8")
    (run_dir / "notes.txt").write_text("not a worker record", encoding="utf-8")

    runs = load_runs(tmp_path)

    assert len(runs) == 1, runs
    assert [worker["worker"] for worker in runs[0]["workers"]] == ["gw1"], runs[0]["workers"]


def test_execute_returns_the_replay_status() -> None:
    """A replay is a debugging entry point: a failing one must not look like a passing one."""

    # A private root, not the suite's ``tmp_path``: the replay runs from the record's rootdir and
    # names a relative file, and a root under ``.tmp/pytest`` would put other tests' live
    # directories one level up from it.
    root = Path(tempfile.mkdtemp(prefix="baluffo-xdist-replay-"))
    try:
        (root / "test_fails.py").write_text(
            "def test_fails() -> None:\n    assert False\n", encoding="utf-8"
        )
        run_dir = root / "run-exec"
        run_dir.mkdir()
        record: dict[str, Any] = {
            "run": "exec",
            "worker": "solo",
            "rootdir": str(root),
            "tests": 1,
            "files": [{"path": "test_fails.py", "tests": 1}],
        }
        (run_dir / "worker-solo.json").write_text(json.dumps(record), encoding="utf-8")

        assert main(["--root", str(root), "--execute"]) == 1
    finally:
        shutil.rmtree(root, ignore_errors=True)


def test_worker_records_sort_by_number_not_by_string(tmp_path: Path) -> None:
    """gw10 is a later worker than gw2; a string sort would report it as the first one."""

    run_dir = tmp_path / "run-order"
    run_dir.mkdir()
    for worker in ("gw10", "gw2", "solo"):
        record: dict[str, Any] = {
            "run": "order",
            "worker": worker,
            "rootdir": str(tmp_path),
            "tests": 0,
            "files": [],
        }
        (run_dir / f"worker-{worker}.json").write_text(json.dumps(record), encoding="utf-8")

    assert [worker["worker"] for worker in load_runs(tmp_path)[0]["workers"]] == [
        "gw2",
        "gw10",
        "solo",
    ]


def test_no_records_is_an_empty_list_not_an_error(tmp_path: Path) -> None:
    """A checkout that has never run the lane must report nothing, not raise."""

    assert load_runs(tmp_path / "missing") == []
    assert load_runs(tmp_path) == []
