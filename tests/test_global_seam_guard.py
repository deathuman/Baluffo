"""Self-test for the suite-wide global-seam guard in :mod:`tests.helpers.global_seam_guard`.

The failure this guard exists for reported itself as a container-gateway ETag assertion in one file
while the leak happened in another, and only under ``-n 4`` where the two shared a worker. A guard
that stops detecting is invisible -- the suite simply goes green -- and a guard that over-detects
is worse, because it gets waived. So these tests pin both directions:

* the fixture is registered for this session (the suite's conftest re-exports it by name),
* a watched seam whose object was replaced is named, and goes quiet once the patch is undone,
* a shadowed ``open`` on the module's opener is named -- the bug's own signature, which an
  identity comparison misses,
* urllib's *lazy* build of that opener, and a second access to a bound ``open``, are not findings,
* the fixture really fails a test that forgets to restore, and does not fail one that patches the
  same seam through ``monkeypatch`` -- driven end to end in a child pytest process that loads the
  same fixture as a plugin.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import tempfile
import unittest.mock
import urllib.request
from pathlib import Path

import pytest

from tests.helpers.global_seam_guard import (
    IDENTITY_SEAMS,
    current_global_seams,
    leaked_global_seams,
)

_REPO_ROOT = Path(__file__).resolve().parents[1]

# The child lives outside ``tests/``, so no repo conftest applies to it: the only guard in its
# process is the fixture loaded with ``-p tests.helpers.global_seam_guard``. That is the point --
# it is the same object the suite registers, so what fails here fails in the suite.
_CHILD_MODULE = '''"""Generated by tests/test_global_seam_guard.py: the leaking pattern and the sanctioned one."""

from __future__ import annotations

import urllib.request
from unittest import mock


def _shadowed_opener():
    """The bug's shape: a real opener whose ``open`` is not the real method."""
    opener = urllib.request.OpenerDirector()
    opener.open = mock.MagicMock()
    return opener


def test_child_leaks() -> None:
    """Installed with no restore: the shadow outlives the test."""
    urllib.request._opener = _shadowed_opener()


def test_child_leaks_urlopen() -> None:
    """``start()`` with no ``stop()``: a watched callable outlives the test."""
    patcher = mock.patch.object(urllib.request, "urlopen", mock.MagicMock())
    patcher.start()


def test_child_clean(monkeypatch) -> None:
    """Patched through ``monkeypatch``, whose teardown runs before the guard's comparison."""
    monkeypatch.setattr(urllib.request, "urlopen", mock.MagicMock())
    monkeypatch.setattr(urllib.request, "_opener", _shadowed_opener())
    assert urllib.request.urlopen is not None


def test_child_lazy_build_is_not_a_leak() -> None:
    """urllib building its opener for the first time is normal, not a finding.

    ``_opener`` is cleared and a real ``urlopen`` raises it again through ``build_opener``. The
    connection is refused, which is the point: the build happens before any socket is used.
    """
    urllib.request._opener = None
    try:
        urllib.request.urlopen("http://127.0.0.1:9/never", timeout=0.2)
    except Exception:
        pass
    assert urllib.request._opener is not None
'''


def _run_child(selection: str) -> subprocess.CompletedProcess[str]:
    """Run one generated child test in its own pytest process with the guard loaded as a plugin.

    The child runs *from* its own directory, with that directory as rootdir, and the file named
    relatively. pytest resolves a path argument against the invocation directory and collects the
    intermediate directories it walked, so an absolute path under the shared temp root made this
    child collect every sibling there -- including directories other processes create and delete
    mid-run (a disappearing ``playwright_chromiumdev_profile-*`` interrupted collection). Nothing
    above the child's own directory is reachable this way, and the repo stays importable through
    ``PYTHONPATH``.
    """

    child_root = Path(tempfile.mkdtemp(prefix="baluffo-global-seam-child-"))
    try:
        child = child_root / "test_global_seam_child.py"
        child.write_text(_CHILD_MODULE, encoding="utf-8")
        env = dict(os.environ)
        env["PYTHONPATH"] = str(_REPO_ROOT)
        env.pop("PYTEST_ADDOPTS", None)
        return subprocess.run(
            [
                sys.executable,
                "-m",
                "pytest",
                child.name,
                "-q",
                "--color=no",
                "--rootdir",
                str(child_root),
                "--basetemp",
                str(child_root / "basetemp"),
                "-p",
                "no:cacheprovider",
                "-p",
                "tests.helpers.global_seam_guard",
                "-k",
                selection,
            ],
            cwd=child_root,
            env=env,
            capture_output=True,
            text=True,
            timeout=300,
        )
    finally:
        shutil.rmtree(child_root, ignore_errors=True)


def test_guard_fixture_is_registered_for_this_session(request: pytest.FixtureRequest) -> None:
    """The conftest's re-export is what makes the guard autouse; asking for it proves it is there."""

    request.getfixturevalue("global_seam_guard")


def test_snapshot_watches_every_named_seam() -> None:
    """Every identity seam resolves in this process, so none is silently unwatched."""

    assert set(IDENTITY_SEAMS) <= set(current_global_seams())


def test_detector_names_a_seam_whose_object_was_replaced() -> None:
    """A seam still holding the replacement is named; restoring it clears the finding."""

    before = current_global_seams()
    with unittest.mock.patch.object(urllib.request, "urlopen", unittest.mock.MagicMock()):
        changed = leaked_global_seams(before)

    assert any(entry.startswith("urllib.request.urlopen: ") for entry in changed), changed
    assert any("MagicMock" in entry for entry in changed), changed
    assert leaked_global_seams(before) == [], (
        "a seam kept the replacement after the patch was undone"
    )


def test_detector_names_a_shadow_on_the_installed_opener() -> None:
    """The bug's own shape: the same module state with a replaced ``open`` is still a leak."""

    before = current_global_seams()
    original = getattr(urllib.request, "_opener", None)
    opener = urllib.request.OpenerDirector()
    # ``_opener`` is private module state and ``open`` is a class method, so both are installed
    # through the object's own dict: neither is in the stubs, and ``setattr`` with a literal name
    # is what the linter rewrites back to the attribute assignment the type checker rejects.
    vars(opener)["open"] = unittest.mock.MagicMock()
    vars(urllib.request)["_opener"] = opener
    try:
        changed = leaked_global_seams(before)
    finally:
        vars(urllib.request)["_opener"] = original

    assert any(entry.startswith("urllib.request._opener.open: ") for entry in changed), changed


def test_a_lazy_opener_build_and_a_bound_method_are_not_findings() -> None:
    """The two shapes that must stay silent, or the guard fails innocent tests by the hundred.

    ``urllib`` builds ``_opener`` on the first ``urlopen`` (``None`` -> an ``OpenerDirector``),
    which is what the suite does constantly; and every access to ``opener.open`` makes a new bound
    method, so an identity comparison on it is never equal even when nothing leaked. Both were
    measured as false positives across ``tests/bridge/test_container_runtime.py`` before this
    guard was narrowed to state.
    """

    original = getattr(urllib.request, "_opener", None)
    try:
        # Whatever the seam held when the test began, a still-unbuilt opener followed by a build
        # is what urllib does on the first ``urlopen`` -- and it must not be a finding.
        vars(urllib.request)["_opener"] = None
        before = current_global_seams()
        assert leaked_global_seams(before) == [], "an unbuilt opener was reported as a leak"
        vars(urllib.request)["_opener"] = urllib.request.OpenerDirector()
        assert leaked_global_seams(before) == [], "a lazy build was reported as a leak"
        opener = vars(urllib.request)["_opener"]
        first, second = opener.open, opener.open
        assert first is not second, "the identity trap this guard must not fall into"
    finally:
        vars(urllib.request)["_opener"] = original


def test_guard_fails_a_test_that_forgets_to_restore() -> None:
    """The leaking pattern must fail, with the guard naming both the test and the seam."""

    proc = _run_child("test_child_leaks")

    output = proc.stdout + proc.stderr
    assert proc.returncode != 0, f"the leaking child passed:\n{output}"
    marker = "process-global seam left changed by "
    start = output.find(marker)
    assert start != -1, f"the child failed without the guard naming the seam:\n{output}"
    # The nodeid of a file passed by relative name still carries its directory as rootdir does not
    # apply, so match the tail of it and the seam inside the same message.
    named = output[start : start + 400]
    assert "test_global_seam_child.py::test_child_leaks" in named, named
    assert "urllib.request._opener.open: MagicMock" in named, named


def test_guard_fails_a_test_that_leaves_urlopen_patched() -> None:
    """The plain ``start()``-without-``stop()`` shape the identity comparison exists for."""

    proc = _run_child("test_child_leaks_urlopen")

    output = proc.stdout + proc.stderr
    assert proc.returncode != 0, f"the leaking child passed:\n{output}"
    assert "urllib.request.urlopen: urllib.request.urlopen -> MagicMock" in output, output


def test_the_sanctioned_patch_is_not_flagged() -> None:
    """``monkeypatch`` restores before the guard looks, so this child must pass."""

    proc = _run_child("test_child_clean")

    output = proc.stdout + proc.stderr
    assert proc.returncode == 0, f"the sanctioned child failed:\n{output}"
    assert "process-global seam left changed" not in output, output


def test_a_lazy_opener_build_is_not_flagged() -> None:
    """urllib's own first ``urlopen`` builds the opener; that test must pass."""

    proc = _run_child("test_child_lazy_build_is_not_a_leak")

    output = proc.stdout + proc.stderr
    assert proc.returncode == 0, f"the lazy-build child failed:\n{output}"
    assert "process-global seam left changed" not in output, output
