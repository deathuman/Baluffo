"""Self-test for the suite-wide compat-seam guard in :mod:`tests.helpers.compat_seams`.

That guard is all that stands between a mocked facade binding and an unrelated test's rows being
rewritten -- the failure it was written for reported itself as a corpus parity identity mismatch
in a *different* file. A guard that stops detecting is invisible: the suite simply goes green. So
these tests pin all three of its parts:

* the fixture is registered for this session (the suite's conftest re-exports it by name),
* the detector names a double on every seam it lists, and fires on none of the real bindings, and
* the fixture really fails a test that leaks through the shim -- driven end to end in a child
  pytest process that loads the same fixture as a plugin.
"""

from __future__ import annotations

import importlib
import os
import subprocess
import sys
import unittest.mock
from pathlib import Path

import pytest

from tests.helpers.compat_seams import COMPAT_SEAM_LEAVES, leaked_compat_seams

_REPO_ROOT = Path(__file__).resolve().parents[1]

# The child lives outside ``tests/``, so no repo conftest applies to it: the only guard in its
# process is the fixture loaded with ``-p tests.helpers.compat_seams``. That is the point -- it is
# the same object the suite registers, so what fails here fails in the suite.
_CHILD_MODULE = '''"""Generated by tests/test_compat_seam_guard.py: the leaking pattern and the sanctioned one."""

from __future__ import annotations

from pathlib import Path
from unittest import mock

from src import jobs_fetcher as jf
from tests.helpers.compat_seams import patched_root_redirect_resolver

_RUN = {
    "run_id": "compat-seam-child",
    "force_refresh_all": True,
    "browser_fallback_max_workers": 0,
    "max_workers": 1,
    "show_progress": False,
}


def _loader(**_: object) -> list[dict[str, object]]:
    """One row, public-looking link, no fetches -- the smallest run that reaches the shim."""

    return [
        {
            "title": "Senior Engineer",
            "company": "Loopback Studio",
            "city": "Remote",
            "country": "Remote",
            "workType": "Remote",
            "contractType": "Full-time",
            "jobLink": "https://boards.example.com/jobs/senior-engineer",
            "sector": "Game",
            "sourceJobId": "child-1",
            "postedAt": "2026-03-01",
        }
    ]


def _never_fetch(url: str, timeout_s: int) -> str:
    """The run tolerates no network, so a fetch here is a finding rather than a slow test."""

    raise AssertionError(f"the child run must not fetch: {url}")


class _FakeResolver:
    def resolve(self, url: str) -> str:
        return "https://jobs.smartrecruiters.com/Ubisoft2/744000108777145-role"

    def snapshot_stats(self) -> dict[str, int]:
        return {}

    def close(self) -> None:
        return None


def test_child_leaks(tmp_path: Path) -> None:
    """A plain facade mock: the shim keeps the copy, so the guard must fail this test."""

    with mock.patch.object(jf, "build_redirect_resolver", return_value=_FakeResolver()):
        jf.run_pipeline(
            output_dir=tmp_path / "leak",
            fetch_text=_never_fetch,
            source_loaders=[("loopback", _loader)],
            **_RUN,
        )


def test_child_clean(tmp_path: Path) -> None:
    """Patched through the helper, which restores the seam, so this one must pass."""

    with patched_root_redirect_resolver(_FakeResolver()):
        jf.run_pipeline(
            output_dir=tmp_path / "clean",
            fetch_text=_never_fetch,
            source_loaders=[("loopback", _loader)],
            **_RUN,
        )
'''


def _run_child(tmp_path: Path, selection: str) -> subprocess.CompletedProcess[str]:
    """Run one generated child test in its own pytest process with the guard loaded as a plugin."""

    child = tmp_path / "test_compat_seam_child.py"
    child.write_text(_CHILD_MODULE, encoding="utf-8")
    env = dict(os.environ)
    env["PYTHONPATH"] = str(_REPO_ROOT)
    # This child is a deliberate single file in the repo's own checkout; the conftest's session
    # lock exists for competing sessions and must not lock it out.
    env["PYTEST_XDIST_WORKER"] = "compat-seam-selfcheck"
    env.pop("PYTEST_ADDOPTS", None)
    return subprocess.run(
        [
            sys.executable,
            "-m",
            "pytest",
            str(child),
            "-q",
            "--color=no",
            "-p",
            "no:cacheprovider",
            "-p",
            "tests.helpers.compat_seams",
            "-k",
            selection,
        ],
        cwd=_REPO_ROOT,
        env=env,
        capture_output=True,
        text=True,
        timeout=300,
    )


def test_guard_fixture_is_registered_for_this_session(request: pytest.FixtureRequest) -> None:
    """The conftest's re-export is what makes the guard autouse; asking for it proves it is there."""

    request.getfixturevalue("compat_seam_guard")


def test_detector_names_a_double_on_every_seam_it_lists() -> None:
    """Each listed seam is watched, and the real bindings are not flagged."""

    for module_name, attribute in COMPAT_SEAM_LEAVES:
        module = importlib.import_module(module_name)
        with unittest.mock.patch.object(module, attribute, unittest.mock.MagicMock(), create=True):
            assert f"{module_name}.{attribute}" in leaked_compat_seams()

    assert leaked_compat_seams() == [], "a seam kept the double after the patch was undone"


def test_guard_fails_a_facade_mock_that_leaks_through_the_shim(tmp_path: Path) -> None:
    """The pattern that broke CI: a plain facade mock, kept by the shim, must fail the guard."""

    proc = _run_child(tmp_path, "test_child_leaks")

    output = proc.stdout + proc.stderr
    assert proc.returncode != 0, f"the leaking child passed:\n{output}"
    assert (
        "compat seam left holding a test double: src.jobs.pipeline.build_redirect_resolver"
        in output
    ), f"the child failed without the guard naming the seam:\n{output}"


def test_sanctioned_helper_child_run_is_not_flagged(tmp_path: Path) -> None:
    """The other direction: patched through the helper, the same run ends with no guard failure."""

    proc = _run_child(tmp_path, "test_child_clean")

    output = proc.stdout + proc.stderr
    assert proc.returncode == 0, f"the sanctioned child failed:\n{output}"
    assert "compat seam left holding a test double" not in output, output
